import { useMemo, useState } from 'react';
import {
  Atom,
  Bookmark,
  BookmarkCheck,
  CheckCircle2,
  Compass,
  GraduationCap,
  Layers,
  Lightbulb,
  Orbit,
  Play,
  Search,
  Sparkles,
  Zap
} from 'lucide-react';
import { CATEGORIES, VISUAL_CATALOG } from './catalog';
import type { VisualizationExperience, AIVisualizationData, VisualCategory } from './types';
import VisualExperiencePlayer from './VisualExperiencePlayer';

interface VisualLearningStudioProps {
  profile: { name: string; grade: string; board: string; subjects: string[] } | null;
  savedVisualIds: string[];
  completedVisualIds: string[];
  onToggleBookmark: (id: string) => void;
  onCompleteExperience: (id: string, title: string) => void;
  onNavigateTopic: (topic: string, subject?: string) => void;
  askAI: (task: string, input: any) => Promise<any>;
}

export default function VisualLearningStudio({
  profile,
  savedVisualIds,
  completedVisualIds,
  onToggleBookmark,
  onCompleteExperience,
  onNavigateTopic,
  askAI
}: VisualLearningStudioProps) {
  const [selectedGrade, setSelectedGrade] = useState(profile?.grade || 'Class 10');
  const [selectedCategory, setSelectedCategory] = useState<string>('All');
  const [selectedSubject, setSelectedSubject] = useState('All');
  const [searchQuery, setSearchQuery] = useState('');
  const [activeExperience, setActiveExperience] = useState<VisualizationExperience | null>(null);
  const [activeAiData, setActiveAiData] = useState<AIVisualizationData | null>(null);

  // AI Topic Exploration State
  const [aiTopicInput, setAiTopicInput] = useState('');
  const [aiLoading, setAiLoading] = useState(false);
  const [aiError, setAiError] = useState('');

  // Filtered visual experiences
  const filteredCatalog = useMemo(() => {
    return VISUAL_CATALOG.filter(item => {
      // Bookmark filter
      if (selectedCategory === 'Saved') {
        if (!savedVisualIds.includes(item.id)) return false;
      } else if (selectedCategory !== 'All' && item.category !== selectedCategory) {
        return false;
      }

      // Subject filter
      if (selectedSubject !== 'All' && item.subject !== selectedSubject) {
        return false;
      }

      // Search query
      if (searchQuery.trim()) {
        const q = searchQuery.toLowerCase();
        const match =
          item.title.toLowerCase().includes(q) ||
          item.description.toLowerCase().includes(q) ||
          item.subject.toLowerCase().includes(q) ||
          item.category.toLowerCase().includes(q);
        if (!match) return false;
      }

      return true;
    });
  }, [selectedCategory, selectedSubject, searchQuery, savedVisualIds]);

  // AI Generation Handler
  const handleGenerateAiVisual = async (topicToUse?: string) => {
    const q = (topicToUse || aiTopicInput).trim();
    if (!q) {
      setAiError('Please enter a scientific or mathematical topic to explore.');
      return;
    }

    setAiLoading(true);
    setAiError('');

    try {
      const result = await askAI('visualize', {
        topic: q,
        profile,
        grade: selectedGrade
      });

      // Validate schema
      if (!result || typeof result !== 'object' || !result.title || !Array.isArray(result.components)) {
        throw new Error('Buddy could not create a structured model for this topic. Please try again.');
      }

      const aiData: AIVisualizationData = {
        title: result.title || `Visual Model: ${q}`,
        subject: result.subject || 'Science',
        topic: result.topic || q,
        description: result.description || 'A structured visual learning model generated by Buddy.',
        category: result.category || 'General Science',
        visualizationType: result.visualizationType || 'process-pipeline',
        components: result.components || [],
        steps: result.steps || [],
        interactiveParameters: result.interactiveParameters || [],
        keyTakeaway: result.keyTakeaway || 'Observe the sequential relationship between components.',
        formulaOrRule: result.formulaOrRule,
        funFact: result.funFact,
        demo: result.demo
      };

      const syntheticExp: VisualizationExperience = {
        id: `ai-${Date.now()}`,
        title: aiData.title,
        subject: aiData.subject,
        category: aiData.category,
        gradeRange: selectedGrade,
        grades: [selectedGrade],
        description: aiData.description,
        badge: 'Guided Diagram',
        components: aiData.components,
        steps: aiData.steps,
        relatedConcepts: [],
        funFact: aiData.funFact,
        formulaOrRule: aiData.formulaOrRule
      };

      setActiveAiData(aiData);
      setActiveExperience(syntheticExp);
    } catch (err: any) {
      console.error('AI visualization generation error:', err);
      setAiError(err.message || 'Could not generate visual model. Please try again.');
    } finally {
      setAiLoading(false);
    }
  };

  // If an active experience is selected, open the dedicated player
  if (activeExperience) {
    return (
      <VisualExperiencePlayer
        experience={activeExperience}
        aiData={activeAiData || undefined}
        isBookmarked={savedVisualIds.includes(activeExperience.id)}
        isCompleted={completedVisualIds.includes(activeExperience.id)}
        onToggleBookmark={onToggleBookmark}
        onCompleteExperience={onCompleteExperience}
        onBack={() => {
          setActiveExperience(null);
          setActiveAiData(null);
        }}
        onNavigateTopic={onNavigateTopic}
      />
    );
  }

  const sampleAiTopics = [
    'How DNA replication works',
    'How a pulley multiplies force',
    'Explain the digestive system',
    'How a volcano erupts',
    'How an electric transformer works'
  ];

  return (
    <section className="visual-studio-page">
      {/* Page Header */}
      <div className="page-heading">
        <span className="eyebrow">FEATURE 06 · INTERACTIVE MODELS</span>
        <h1>Visual Learning Studio</h1>
        <p>
          Understand how science, nature, mathematics, and technology really work through interactive diagrams, step-by-step simulations, and genuine 3D models.
        </p>
      </div>

      {/* Header Filters & Controls */}
      <div className="panel studio-filter-panel">
        <div className="studio-filter-grid">
          {/* Class / Grade Selector */}
          <div className="video-field">
            <label className="field-label">TARGET CLASS</label>
            <select
              className="form-input"
              value={selectedGrade}
              onChange={e => setSelectedGrade(e.target.value)}
            >
              {Array.from({ length: 12 }, (_, i) => `Class ${i + 1}`).map(g => (
                <option key={g}>{g}</option>
              ))}
            </select>
          </div>

          {/* Subject Selector */}
          <div className="video-field">
            <label className="field-label">SUBJECT</label>
            <select
              className="form-input"
              value={selectedSubject}
              onChange={e => setSelectedSubject(e.target.value)}
            >
              <option value="All">All Subjects</option>
              <option value="Science">Science</option>
              <option value="Biology">Biology</option>
              <option value="Physics">Physics</option>
              <option value="Chemistry">Chemistry</option>
              <option value="Mathematics">Mathematics</option>
              <option value="Geography">Geography</option>
            </select>
          </div>

          {/* Search Box */}
          <div className="video-field" style={{ gridColumn: 'span 2' }}>
            <label className="field-label">SEARCH MODELS</label>
            <div className="search-field">
              <Search size={16} />
              <input
                value={searchQuery}
                onChange={e => setSearchQuery(e.target.value)}
                placeholder="Search by topic, e.g. Heart, Solar, Circuit, Optics, Atom, Water..."
              />
            </div>
          </div>
        </div>

        {/* Category Pills & Saved Tab */}
        <div className="studio-category-row">
          {CATEGORIES.map(cat => (
            <button
              key={cat}
              className={`category-pill ${selectedCategory === cat ? 'active' : ''}`}
              onClick={() => setSelectedCategory(cat)}
            >
              {cat}
            </button>
          ))}
          <button
            className={`category-pill ${selectedCategory === 'Saved' ? 'active' : ''}`}
            onClick={() => setSelectedCategory('Saved')}
          >
            <Bookmark size={13} /> Saved ({savedVisualIds.length})
          </button>
        </div>
      </div>

      {/* AI Visual Exploration Card */}
      <div className="panel ai-visual-generator-card">
        <div className="ai-gen-header">
          <div className="dash-stat-icon purple">
            <Sparkles size={20} />
          </div>
          <div>
            <h3>AI Visual Model Generator</h3>
            <p>
              Want to see how something else works? Enter any topic and Buddy will generate an interactive visual explanation.
            </p>
          </div>
        </div>

        <div className="ai-gen-form">
          <div className="search-field" style={{ flex: 1 }}>
            <Sparkles size={16} className="text-green" />
            <input
              value={aiTopicInput}
              onChange={e => setAiTopicInput(e.target.value)}
              onKeyDown={e => e.key === 'Enter' && !aiLoading && handleGenerateAiVisual()}
              placeholder="e.g. How does DNA replication work? How does a pulley work?"
              disabled={aiLoading}
            />
          </div>
          <button
            className="btn btn-primary"
            onClick={() => handleGenerateAiVisual()}
            disabled={aiLoading || !aiTopicInput.trim()}
          >
            {aiLoading ? <span className="spinner" /> : <Sparkles size={16} />}
            {aiLoading ? 'Generating Model...' : 'Build Visual Model'}
          </button>
        </div>

        {aiError && <p className="video-error">{aiError}</p>}

        <div className="ai-suggestions-row">
          <span>Try:</span>
          {sampleAiTopics.map(t => (
            <button
              key={t}
              className="ai-suggestion-chip"
              onClick={() => { setAiTopicInput(t); handleGenerateAiVisual(t); }}
              disabled={aiLoading}
            >
              {t}
            </button>
          ))}
        </div>
      </div>

      {/* Catalog Cards Grid */}
      <div className="section-title">
        <div>
          <span className="eyebrow">INTERACTIVE LIBRARY</span>
          <h2>Explore Visual Experiences</h2>
        </div>
        <span className="task-count">
          {filteredCatalog.length} available
        </span>
      </div>

      {filteredCatalog.length === 0 ? (
        <div className="panel empty-state">
          <div className="empty-illustration">
            <Compass size={32} />
          </div>
          <h3>No visual models found</h3>
          <p>
            {selectedCategory === 'Saved'
              ? 'You have not saved any visualizations yet. Bookmark models using the ribbon icon to keep them here.'
              : 'Try broadening your search or switching categories.'}
          </p>
          <button
            className="btn btn-primary"
            onClick={() => { setSelectedCategory('All'); setSearchQuery(''); setSelectedSubject('All'); }}
          >
            Show All Models
          </button>
        </div>
      ) : (
        <div className="visual-cards-grid">
          {filteredCatalog.map(item => {
            const isBookmarked = savedVisualIds.includes(item.id);
            const isCompleted = completedVisualIds.includes(item.id);

            return (
              <div className="panel visual-card" key={item.id}>
                {/* Visual Card Header */}
                <div className="visual-card-thumb">
                  <div className="visual-card-badge-row">
                    <span className="visual-type-badge">{item.badge}</span>
                    <span className="visual-grade-badge">{item.gradeRange}</span>
                  </div>

                  {/* Icon illustration preview */}
                  <div className="visual-thumb-icon">
                    {item.id === 'solar-system' && <Orbit size={48} className="text-yellow" />}
                    {item.id === 'human-heart' && <span className="custom-emoji">🫀</span>}
                    {item.id === 'photosynthesis' && <span className="custom-emoji">🌿</span>}
                    {item.id === 'electric-circuit' && <Zap size={48} className="text-yellow" />}
                    {item.id === 'reflection-refraction' && <span className="custom-emoji">🔦</span>}
                    {item.id === 'atomic-structure' && <Atom size={48} className="text-blue" />}
                    {item.id === 'geometry-explorer' && <span className="custom-emoji">📐</span>}
                    {item.id === 'water-cycle' && <span className="custom-emoji">🌊</span>}
                  </div>

                  {isCompleted && (
                    <span className="completed-check-tag">
                      <CheckCircle2 size={13} /> Completed
                    </span>
                  )}
                </div>

                {/* Card Body */}
                <div className="visual-card-body">
                  <div className="visual-meta-tags">
                    <span className="rev-subject">{item.subject}</span>
                    <span className="visual-category-tag">{item.category}</span>
                  </div>

                  <h3>{item.title}</h3>
                  <p>{item.description}</p>

                  <div className="visual-card-actions">
                    <button
                      className="btn btn-primary"
                      onClick={() => {
                        setActiveExperience(item);
                        setActiveAiData(null);
                      }}
                    >
                      <Play size={14} /> Launch Model
                    </button>

                    <button
                      className={`icon-btn ${isBookmarked ? 'btn-bookmarked' : ''}`}
                      onClick={() => onToggleBookmark(item.id)}
                      aria-label={isBookmarked ? 'Remove bookmark' : 'Bookmark visualization'}
                      title={isBookmarked ? 'Remove bookmark' : 'Bookmark visualization'}
                    >
                      {isBookmarked ? <BookmarkCheck size={18} className="text-green" /> : <Bookmark size={18} />}
                    </button>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      )}
    </section>
  );
}
